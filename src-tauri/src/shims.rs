use std::path::PathBuf;

use serde::Serialize;

use crate::error::{AppError, Result};
use crate::platform;
use crate::profiles::{Env, Profile};

/// Marker embedded in every generated shim. Removal and overwrite are only
/// allowed on files carrying it, so we never clobber a user's own script.
const MARKER: &str = "claude-switcher:profile=";

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ShimStatus {
    pub installed: bool,
    pub path: Option<PathBuf>,
    pub on_path: bool,
    /// True when the shim exists but points at a different config dir than
    /// the profile (e.g. config was restored from backup) — offer regenerate.
    pub drifted: bool,
}

fn shim_dir(env: &Env) -> Result<PathBuf> {
    // Settings override is resolved by the caller via Store; Env carries
    // the platform default only.
    let _ = env;
    platform::default_shim_dir()
        .ok_or_else(|| AppError::not_found("could not determine a shim directory"))
}

fn shim_path(profile: &Profile, env: &Env) -> Result<PathBuf> {
    if profile.code.shim_name.is_empty() {
        return Err(AppError::validation(
            "the default profile does not need a shim — plain `claude` already uses it",
        ));
    }
    Ok(shim_dir(env)?.join(&profile.code.shim_name))
}

fn render(profile: &Profile) -> String {
    format!(
        "#!/bin/sh\n# {MARKER}{id} — generated by Claude Account Switcher, do not edit\nexport CLAUDE_CONFIG_DIR=\"{dir}\"\nexec claude \"$@\"\n",
        id = profile.id,
        dir = profile.code.config_dir.display(),
    )
}

fn is_ours(content: &str) -> bool {
    content.lines().nth(1).is_some_and(|l| l.contains(MARKER))
}

fn dir_on_path(dir: &PathBuf) -> bool {
    std::env::var_os("PATH")
        .map(|paths| std::env::split_paths(&paths).any(|p| &p == dir))
        .unwrap_or(false)
}

pub fn install(profile: &Profile, env: &Env) -> Result<ShimStatus> {
    let path = shim_path(profile, env)?;
    if let Ok(existing) = std::fs::read_to_string(&path) {
        if !is_ours(&existing) {
            return Err(AppError::validation(format!(
                "{} already exists and was not created by this app",
                path.display()
            )));
        }
    }
    let dir = shim_dir(env)?;
    std::fs::create_dir_all(&dir)?;
    std::fs::write(&path, render(profile))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755))?;
    }
    Ok(ShimStatus {
        installed: true,
        on_path: dir_on_path(&dir),
        path: Some(path),
        drifted: false,
    })
}

/// Returns true if a shim was actually removed.
pub fn remove(profile: &Profile, env: &Env) -> Result<bool> {
    let path = match shim_path(profile, env) {
        Ok(p) => p,
        Err(_) => return Ok(false), // default profile: nothing to remove
    };
    match std::fs::read_to_string(&path) {
        Ok(content) if is_ours(&content) => {
            std::fs::remove_file(&path)?;
            Ok(true)
        }
        Ok(_) => Err(AppError::validation(format!(
            "{} was not created by this app — refusing to delete it",
            path.display()
        ))),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(e) => Err(e.into()),
    }
}

pub fn status(profile: &Profile, env: &Env) -> Result<ShimStatus> {
    let path = shim_path(profile, env)?;
    let dir = shim_dir(env)?;
    match std::fs::read_to_string(&path) {
        Ok(content) if is_ours(&content) => Ok(ShimStatus {
            installed: true,
            on_path: dir_on_path(&dir),
            drifted: content != render(profile),
            path: Some(path),
        }),
        _ => Ok(ShimStatus {
            installed: false,
            on_path: dir_on_path(&dir),
            drifted: false,
            path: Some(path),
        }),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::profiles::{CodeConfig, DesktopConfig};
    use std::path::Path;

    fn test_profile(config_dir: &Path) -> Profile {
        Profile {
            id: "test-id".into(),
            name: "Work".into(),
            slug: "work".into(),
            color: "#fff".into(),
            is_default: false,
            desktop: DesktopConfig {
                enabled: true,
                user_data_dir: PathBuf::from("/tmp/x"),
            },
            code: CodeConfig {
                enabled: true,
                config_dir: config_dir.to_path_buf(),
                shim_name: "claude-work".into(),
                shim_installed: false,
            },
            created_at: String::new(),
            last_launched_at: None,
        }
    }

    #[test]
    fn render_contains_marker_and_exact_path() {
        let p = test_profile(Path::new("/Users/x/.claude-work"));
        let out = render(&p);
        assert!(out.contains("claude-switcher:profile=test-id"));
        assert!(out.contains("export CLAUDE_CONFIG_DIR=\"/Users/x/.claude-work\""));
        assert!(out.ends_with("exec claude \"$@\"\n"));
        assert!(is_ours(&out));
    }

    #[test]
    fn foreign_files_are_not_ours() {
        assert!(!is_ours("#!/bin/sh\necho hello\n"));
        assert!(!is_ours(""));
    }
}
